# =========================================================
# PCA ANALYSIS
# =========================================================

# =========================================================
# INSTALL PACKAGES
# =========================================================

install.packages("factoextra")

# =========================================================
# LOAD LIBRARIES
# =========================================================

library(factoextra)

# =========================================================
# LOAD DATA
# =========================================================

setwd("G:/R Programming/ML/Predicting Concrete Strength/")

data <- read.csv(
  "G:/R Programming/ML/Predicting Concrete Strength/Raw Data Concrete_Data_Yeh.csv"
)

# =========================================================
# REMOVE TARGET VARIABLE
# =========================================================

x <- data[,1:8]

# =========================================================
# STANDARDIZATION
# =========================================================

x_scaled <- scale(x)

# =========================================================
# PCA MODEL
# =========================================================

pca_model <- prcomp(
  x_scaled,
  center = TRUE,
  scale. = TRUE
)

summary(pca_model)

# =========================================================
# SCREE PLOT
# =========================================================

fviz_eig(
  pca_model,
  
  addlabels = TRUE,
  
  main = "Scree Plot"
)

# =========================================================
# VARIABLE CONTRIBUTION
# =========================================================

fviz_pca_var(
  pca_model,
  
  col.var = "blue",
  
  repel = TRUE
)

# =========================================================
# PCA BIPLOT
# =========================================================

fviz_pca_biplot(
  pca_model,
  
  repel = TRUE,
  
  col.var = "red",
  
  col.ind = "blue"
)