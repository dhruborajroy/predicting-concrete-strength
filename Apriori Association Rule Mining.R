# =========================================================
# APRIORI ASSOCIATION RULES
# =========================================================

# =========================================================
# INSTALL PACKAGES
# =========================================================

install.packages("arules")
install.packages("arulesViz")

# =========================================================
# LOAD LIBRARIES
# =========================================================

library(arules)
library(arulesViz)

# =========================================================
# LOAD DATA
# =========================================================

setwd("G:/R Programming/ML/Predicting Concrete Strength/")

data <- read.csv(
  "G:/R Programming/ML/Predicting Concrete Strength/Raw Data Concrete_Data_Yeh.csv"
)

# =========================================================
# DISCRETIZATION
# =========================================================

data_disc <- discretizeDF.supervised(
  data,
  
  classColumn = 9
)

# =========================================================
# CONVERT TO TRANSACTIONS
# =========================================================

trans <- as(
  data_disc,
  "transactions"
)

# =========================================================
# APRIORI MODEL
# =========================================================

rules <- apriori(
  trans,
  
  parameter = list(
    supp = 0.1,
    conf = 0.8,
    minlen = 2
  )
)

# =========================================================
# VIEW RULES
# =========================================================

inspect(sort(
  rules,
  by = "confidence"
)[1:10])

# =========================================================
# PLOT RULES
# =========================================================

plot(
  rules,
  
  method = "graph"
)